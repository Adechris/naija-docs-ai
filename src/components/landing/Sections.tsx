export function LiveDemo() {
  const [text, setText] = useState("");
  const [running, setRunning] = useState(false);
  const timer = useRef<ReturnType<typeof setInterval> | null>(null);
  const excerpt = SAMPLE_DOCUMENT.slice(0, 720);

  useEffect(() => {
    return () => {
      if (timer.current) clearInterval(timer.current);
    };
  }, []);

  const run = () => {
    if (timer.current) clearInterval(timer.current);
    setText("");
    setRunning(true);
    let i = 0;
    timer.current = setInterval(() => {
      i += 6;
      setText(excerpt.slice(0, i));
      if (i >= excerpt.length) {
        clearInterval(timer.current!);
        setRunning(false);
      }
    }, 16);
  };

  return (
    <section id="features" className="mx-auto max-w-7xl px-4 py-20 sm:px-6">
      <SectionHead label="Live demo" title="Watch DocuAI Work" />
      <div className="mt-12 grid gap-6 lg:grid-cols-2">
        <div className="rounded-lg border border-border bg-card p-6 shadow-card">
          <div className="space-y-4">
            <div className="space-y-1.5">
              <Label htmlFor="demo-parties">Parties involved</Label>
              <Input id="demo-parties" defaultValue="Zenith Retail Ltd & Adeyinka Fashola" />
            </div>
            <div className="space-y-1.5">
              <Label htmlFor="demo-type">Type of contract</Label>
              <Input id="demo-type" defaultValue="Employment Contract" />
            </div>
            <div className="space-y-1.5">
              <Label htmlFor="demo-terms">Key terms</Label>
              <Input id="demo-terms" defaultValue="₦850,000/month, 3-month probation, Lagos" />
            </div>
            <Button onClick={run} disabled={running} className="bg-gradient-blue w-full">
              <Sparkles className="mr-1.5 h-4 w-4" />
              {running ? "Generating…" : "Generate Sample"}
            </Button>
          </div>
        </div>
        <div className="paper min-h-[320px] rounded-lg p-6 text-[12px] leading-relaxed">
          {text ? (
            <pre className="whitespace-pre-wrap font-document">{text}</pre>
          ) : (
            <p className="font-sans text-sm text-muted-foreground">
              Your generated document preview will appear here.
            </p>
          )}
        </div>
      </div>
      <p className="mt-6 text-center text-sm font-medium text-muted-foreground">
        This took 6 seconds.{" "}
        <Link to="/register" className="text-primary underline-offset-4 hover:underline">
          Sign up to generate yours.
        </Link>
      </p>
    </section>
  );
}

