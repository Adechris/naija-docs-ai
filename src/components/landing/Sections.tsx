function FloatCard({
  children,
  className,
  delay,
}: {
  children: React.ReactNode;
  className?: string;
  delay: string;
}) {
  return (
    <div
      style={{ animationDelay: delay }}
      className={`animate-float absolute hidden rounded-lg border border-border bg-card px-3 py-2 text-xs font-semibold shadow-card lg:block ${className}`}
    >
      {children}
    </div>
  );
}

